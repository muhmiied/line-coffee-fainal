export function normalizeAdminText(value: string): string {
  return value.replace(/\u00a0/g, " ").replace(/\s+/g, " ").trim();
}

export function translateAdminText(value: string, language: AdminLanguage): string {
  if (language === "en") return value;

  const normalized = normalizeAdminText(value);
  if (!normalized) return value;

  const exact = NORMALIZED_TRANSLATIONS.get(normalized);
  if (exact) return exact;

  if (!/\d/.test(normalized)) return value;

  let translated = normalized;
  for (const [pattern, replacement] of PHRASE_REPLACEMENTS) {
    translated = translated.replace(pattern, replacement);
  }
  return translated === normalized ? value : translated;
}

export function getAdminDirection(language: AdminLanguage): AdminDirection {
  return language === "ar" ? "rtl" : "ltr";
}

export function isAdminLanguage(value: unknown): value is AdminLanguage {
  return value === "en" || value === "ar";
}
